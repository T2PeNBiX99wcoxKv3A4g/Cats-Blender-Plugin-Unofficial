// Copies content that lives outside Site/ into the bundle and turns the plain-JS
// site config into something TypeScript can import:
//
//   ../README.md        -> src/generated/readme.ts
//   ./site.config.mjs   -> src/generated/site.ts
//   git log per doc     -> src/generated/doc-dates.ts
//
// Run automatically before `dev` and `build`.
import {readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync} from "node:fs";
import {execFileSync} from "node:child_process";
import {dirname, resolve, join} from "node:path";
import {fileURLToPath} from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(here, "..");
const repoRoot = resolve(siteRoot, "..");
const outDir = resolve(siteRoot, "src/generated");

mkdirSync(outDir, {recursive: true});

const readmePath = resolve(repoRoot, "README.md");
if (!existsSync(readmePath)) {
    throw new Error(`README.md not found at ${readmePath}`);
}

// The README opens with the project title; the site renders its own header, so the
// leading H1 is dropped to avoid showing the name twice.
const readme = readFileSync(readmePath, "utf8").replace(/^#\s+.*(\r?\n)+/, "");

writeFileSync(
    resolve(outDir, "readme.ts"),
    `// Generated by scripts/sync-content.mjs from the repository README.md.\n` +
    `export const readme = ${JSON.stringify(readme)};\n`,
    "utf8",
);

const {site} = await import(resolve(siteRoot, "site.config.mjs").replace(/\\/g, "/").replace(/^([A-Za-z]):/, "file:///$1:"));

writeFileSync(
    resolve(outDir, "site.ts"),
    `// Generated by scripts/sync-content.mjs from site.config.mjs.\n` +
    `export const site = ${JSON.stringify(site, null, 4)} as const;\n`,
    "utf8",
);

/**
 * Last commit date (YYYY-MM-DD) for a path, from the git history. A shallow clone only
 * contains the checked-out commit, and a file untouched by it returns nothing, so the
 * repository's own last commit date is used as the fallback.
 */
function gitDate(path) {
    const run = (args) => {
        try {
            return execFileSync("git", args, {cwd: repoRoot, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"]}).trim();
        } catch {
            return "";
        }
    };

    return run(["log", "-1", "--format=%cs", "--", path]) || run(["log", "-1", "--format=%cs"]) || "";
}

const docsRoot = resolve(siteRoot, "docs");
const dates = {};

if (existsSync(docsRoot)) {
    for (const language of readdirSync(docsRoot)) {
        const languageDir = join(docsRoot, language);
        if (!statSync(languageDir).isDirectory()) continue;

        for (const file of readdirSync(languageDir)) {
            if (!file.endsWith(".md")) continue;
            const slug = file.slice(0, -".md".length);
            const absolute = join(languageDir, file);
            const date = gitDate(resolve(absolute));
            if (date) dates[`${language}/${slug}`] = date;
        }
    }
}

writeFileSync(
    resolve(outDir, "doc-dates.ts"),
    `// Generated by scripts/sync-content.mjs from the git history.\n` +
    `export const docDates: Record<string, string> = ${JSON.stringify(dates, null, 4)};\n`,
    "utf8",
);

console.log(`synced README (${readme.length} chars), site config and ${Object.keys(dates).length} doc dates`);
