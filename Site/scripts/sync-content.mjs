// Copies content that lives outside Site/ into the bundle and turns the plain-JS
// site config into something TypeScript can import:
//
//   ../README.md      -> src/generated/readme.ts
//   ./site.config.mjs -> src/generated/site.ts
//
// Run automatically before `dev` and `build`.
import {readFileSync, writeFileSync, mkdirSync, existsSync} from "node:fs";
import {dirname, resolve} from "node:path";
import {fileURLToPath} from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(here, "..");
const repoRoot = resolve(siteRoot, "..");
const outDir = resolve(siteRoot, "src/generated");

mkdirSync(outDir, {recursive: true});

const readmePath = resolve(repoRoot, "README.md");
if (!existsSync(readmePath)) {
    throw new Error(`README.md not found at ${readmePath}`);
}

// The README opens with the project title; the site renders its own header, so the
// leading H1 is dropped to avoid showing the name twice.
const readme = readFileSync(readmePath, "utf8").replace(/^#\s+.*(\r?\n)+/, "");

writeFileSync(
    resolve(outDir, "readme.ts"),
    `// Generated by scripts/sync-content.mjs from the repository README.md.\n` +
    `export const readme = ${JSON.stringify(readme)};\n`,
    "utf8",
);

const {site} = await import(resolve(siteRoot, "site.config.mjs").replace(/\\/g, "/").replace(/^([A-Za-z]):/, "file:///$1:"));

writeFileSync(
    resolve(outDir, "site.ts"),
    `// Generated by scripts/sync-content.mjs from site.config.mjs.\n` +
    `export const site = ${JSON.stringify(site, null, 4)} as const;\n`,
    "utf8",
);

console.log(`synced README (${readme.length} chars) and site config`);
